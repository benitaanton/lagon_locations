def lire_texte_pdf(chemin):
    """Renvoie tout le texte d'un PDF, page par page, et l'enregistre a cote.

    On garde une copie du texte brut pour pouvoir, plus tard, comparer ce que
    le modele a compris avec ce qui etait reellement ecrit dans le document.
    """
    lecteur = PdfReader(str(chemin))
    texte = "\n".join(page.extract_text() or "" for page in lecteur.pages)
    (DOSSIER_TEXTE / f"{chemin.stem}.txt").write_text(texte, encoding="utf-8")
    return texte

