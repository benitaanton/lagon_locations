def tableau(lignes, largeurs=(55 * mm, 95 * mm), fond="#f4f4f4"):
    """Fabrique un tableau a deux colonnes : etiquette a gauche, valeur a droite.

    Les regles de TableStyle s'appliquent a une zone de cellules :
      (0, 0), (-1, -1) = de la premiere cellule a la derniere, donc tout le tableau
      (0, 0), (0, -1)  = toute la premiere colonne
    """
    t = Table(lignes, colWidths=largeurs)
    t.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), POLICE),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#444444")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor(fond)),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#dddddd")),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return t


