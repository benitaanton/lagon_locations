def extraire(texte, nom_fichier):
    """Envoie le texte au modele et renvoie le dictionnaire des champs."""
    reponse = client.messages.create(
        model=MODELE,
        max_tokens=1200,
        system=CONSIGNE,
        messages=[{"role": "user", "content": texte}],
    )

    # La reponse peut contenir plusieurs blocs (raisonnement, texte...). On ne
    # prend donc pas le premier venu : on garde uniquement les blocs de texte.
    blocs_texte = [b.text for b in reponse.content if getattr(b, "type", None) == "text"]
    if not blocs_texte:
        raise ValueError("aucun bloc de texte dans la réponse du modèle")
    brut = "\n".join(blocs_texte).strip()

    # Le modele encadre parfois le JSON par ```json ... ``` : on nettoie.
    if brut.startswith("```"):
        brut = brut.split("```")[1]
        if brut.startswith("json"):
            brut = brut[4:]
        brut = brut.strip()

    donnees = json.loads(brut)
    donnees["fichier_source"] = nom_fichier

    (DOSSIER_JSON / f"{Path(nom_fichier).stem}.json").write_text(
        json.dumps(donnees, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return donnees

